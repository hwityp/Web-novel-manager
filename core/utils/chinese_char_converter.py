def to_simplified_chinese(text: str) -> str:
    """
    번체자 한자를 간체자 한자로 변환 (간체자 및 일반 문자는 그대로 보존)
    
    예시:
        '亂世書' -> '乱世书'
        '修仙界' -> '修仙界'
        '鬥羅大陸' -> '斗罗大陆'
    """
    if not text:
        return text
    
    return "".join(TRADITIONAL_TO_SIMPLIFIED_MAP.get(char, char) for char in text)
